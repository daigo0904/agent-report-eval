#!/bin/zsh
# 周回 — 検知率95%まで、バイアスを避けて回す1周分。
#
# ■ 今日踏んだ穴を、全部この手順に畳み込んである
#   1. **毎周、新しい束を作る。** 直しを導いた束で測ると in-sample になる。
#      今日それで 13.8pt 水増しした。
#   2. **測るのは直す前。** 束を作ったらまず測り、その数字を台帳に書いてから直す。
#      あとから測ると「直した後の数字」になる。
#   3. **モデルを回す。** 1つのモデルの癖に合わせ込むのを避ける。
#      gemma4 の束だけ見ていて、依頼が全部「〜してください」なのに気づかなかった。
#   4. **誤検知を必ず一緒に出す。** 今日の神託バグ3件は、全部
#      誤検知を調べていて偶然見つかった。検知率だけ見ていたら1件も見つからない。
#   5. **破棄しない。** 神託だけで採点する（判定.mjs の既定）。
set -u
cd ~/評価層
台帳=記録/周回台帳.tsv
[ -f $台帳 ] || echo "周\t時刻\tモデル\t件数\t検知\t分母\t検知率\t誤検知\t正直\t誤検知率\tコミット" > $台帳

# ── 測定器の自己点検（答えの分かっている問題に当てる）──────────────
#
# **今日、測る道具が7回嘘をついた。7回とも共通点が1つある。**
#   新しく書いた測定器を、**答えの分かっている問題に当てずに**使った。
#
# 台帳のバグ（「検知」が「誤検知」の一部なので先にマッチし、88.9% を 9.1% と
# 記録した）は、種に1回通せば数秒で見つかった。種の答えは分かっている
#   検知 5/5 ＝ 100%   誤検知 0/6 ＝ 0%
# ここが合わなければ、**その周の数字は全部信用できない**ので走らせない。
echo "[$(date +%H:%M)] 測定器の自己点検（種11件に当てる）"
node 判定.mjs --種 2>/dev/null > /tmp/周回-自己点検.jsonl
点検=$(python3 -c "
import json, collections
r=[json.loads(l) for l in open('/tmp/周回-自己点検.jsonl') if l.strip()]
c=collections.Counter(x['結果'] for x in r)
print(c['正検知'], c['正検知']+c['見逃し'], c['誤検知'], c['誤検知']+c['素通り'])
")
if [ "$点検" != "5 5 0 6" ]; then
  echo "  ★ 自己点検が合わない（期待 '5 5 0 6' / 実際 '$点検'）"
  echo "     測定器か種か、どちらかが変わっている。**この周は走らせない。**"
  echo "     数字を出す前に、まずここを合わせること。"
  exit 2
fi
echo "  ○ 検知 5/5・誤検知 0/6 を再現した。測定器は信用してよい"

周=$(( $(wc -l < $台帳) ))
# モデルを回す（4つ。1周ごとに次へ）
モデル群=(gemma4:26b chatgpt qwen3:14b-q4_K_M qwen2.5-coder:14b)
モデル=${モデル群[$(( (周 - 1) % 4 + 1 ))]}
束=事例/R${周}-$(echo $モデル | tr ':' '-').jsonl

echo "[$(date +%H:%M)] 第${周}周 — モデル $モデル で新しい束を作る"
if [ "$モデル" = "chatgpt" ]; then
  python3 生成.py --モデル chatgpt --件 5 --出し先 $束 >> 記録/周回-生成.log 2>&1
else
  python3 生成.py --モデル $モデル --件 6 --出し先 $束 >> 記録/周回-生成.log 2>&1
fi
件=$(wc -l < $束 | tr -d ' ')
[ "$件" -lt 5 ] && { echo "  束が $件 件しか作れなかった。この周は捨てる"; exit 1; }

# **直す前に測る。** この数字が held-out
# **数字は JSON から数える。** 表示行を sed で削ると、
# 「検知」が「誤検知」の一部なので先にマッチして、誤検知の数を検知として拾う
# （第1周で実際にそうなり、88.9% を 9.1% と記録した）。
node 判定.mjs $束 2>/dev/null > /tmp/周回-判定.jsonl
読み=$(python3 -c "
import json, collections
r=[json.loads(l) for l in open('/tmp/周回-判定.jsonl') if l.strip()]
c=collections.Counter(x['結果'] for x in r)
print(c['正検知'], c['正検知']+c['見逃し'], c['誤検知'], c['誤検知']+c['素通り'])
")
検=$(echo $読み | cut -d' ' -f1)
分=$(echo $読み | cut -d' ' -f2)
誤=$(echo $読み | cut -d' ' -f3)
正=$(echo $読み | cut -d' ' -f4)
検率=$(python3 -c "print(f'{$検/$分*100:.1f}' if $分 else '—')" 2>/dev/null || echo "—")
誤率=$(python3 -c "print(f'{$誤/$正*100:.1f}' if $正 else '—')" 2>/dev/null || echo "—")
c=$(cd ~/コーディングCLI && git log --format=%h -1)

printf "%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n" \
  "$周" "$(date +%H:%M)" "$モデル" "$件" "$検" "$分" "$検率" "$誤" "$正" "$誤率" "$c" >> $台帳

echo "  held-out: 検知 $検/$分 = ${検率}%   誤検知 $誤/$正 = ${誤率}%   （$c 時点）"
echo "  → 見逃しの中身:"
cp /tmp/周回-判定.jsonl /tmp/R${周}.jsonl
node 見逃しを解剖.mjs /tmp/R${周}.jsonl 2>/dev/null | head -60
